const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const read = (relativePath) => fs.readFileSync(path.join(root, relativePath), 'utf8')
const assert = (condition, message) => {
  if (!condition) throw new Error(message)
}

const app = read('src/app/App.tsx')
const preferences = read('src/app/workbench-preferences.ts')
const latencyExport = read('src/features/latency-analysis/latency-export.ts')
const latencyContainer = read('src/features/latency-analysis/LatencyAnalysisContainer.tsx')
const healthContainer = read('src/features/health-check/HealthCheckContainer.tsx')
const ruleContainer = read('src/features/rule-config/RuleConfigContainer.tsx')
const logSearchContainer = read('src/features/log-search/LogSearchContainer.tsx')
const legacyClient = read('src/api/tauri-client.ts')

assert(preferences.includes('readActiveScenario'), 'Workbench preferences must own the active scenario preference.')
assert(preferences.includes('pushRecentFolder'), 'Workbench preferences must own recent-folder normalization.')
assert(latencyExport.includes('buildLatencyExportCsv'), 'Latency export must build the CSV outside App.')
assert(latencyExport.includes('downloadCsv'), 'Latency export must own browser download behavior.')
assert(app.includes("from './workbench-preferences'"), 'App must consume the extracted preferences module.')
assert(app.includes("latency-analysis/LatencyAnalysisContainer"), 'App must render the extracted latency container.')
assert(latencyContainer.includes('function LatencyAnalysisContainer'), 'Latency analysis must have a feature container.')
assert(app.includes("health-check/HealthCheckContainer"), 'App must render the extracted issue-tips container.')
assert(healthContainer.includes('function HealthCheckContainer'), 'Issue tips must have a feature container.')
assert(app.includes("rule-config/RuleConfigContainer"), 'App must render the extracted rule-config container.')
assert(ruleContainer.includes('function RuleConfigContainer'), 'Rule config must have a feature container.')
assert(app.includes("log-search/LogSearchContainer"), 'App must render the extracted log-search container.')
assert(logSearchContainer.includes('function LogSearchContainer'), 'Log search must have a feature container.')
assert(!app.includes('function buildLatencyExportCsv'), 'App must not own CSV assembly.')
assert(!app.includes('function runLatencyAnalysis'), 'App must not own latency analysis execution.')
assert(!app.includes('function runHealthCheck'), 'App must not own health-check execution.')
assert(!app.includes('function runDiagnostic'), 'App must not own specialist diagnosis execution.')
assert(!app.includes('function importRules'), 'App must not own rule package editing.')
assert(!app.includes('function runSearch'), 'App must not own log search execution.')
assert(app.includes("<div hidden={activeTabId !== 'latency-analysis'}>"), 'Latency container must stay mounted when switching tabs.')
assert(app.includes("<div hidden={activeTabId !== 'issue-tips'}>"), 'Issue tips container must stay mounted when switching tabs.')
assert(!app.includes('latency-analysis/latency-export'), 'App must not own latency export behavior.')
assert(!app.includes('function readPersistedMatcherIds'), 'App must not own preference persistence.')
assert(!legacyClient.includes('sampleLogLines'), 'Legacy client must not retain sample log data.')
assert(!legacyClient.includes('function localSearch'), 'Legacy client must not retain the unused local log search.')
assert(!fs.existsSync(path.join(root, 'src/app/app-state.ts')), 'Demo app state must be removed.')
assert(!fs.existsSync(path.join(root, 'src/app/app-actions.ts')), 'Demo app actions must be removed.')

console.log('App boundaries passed')
